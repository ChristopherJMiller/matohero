#!/usr/bin/env python3
"""Regenerate docs/progress.md from a reccmp run.

Counts against the game + engine code only: every function Ghidra found below
the statically linked CRT (ghidra/export/functions.csv). Functions are grouped into
original modules through orig/ps2proto/pc_objects.csv when it exists.

  tools/progress.py            run reccmp, rewrite docs/progress.md, print the summary
  tools/progress.py --no-write print only
"""
import argparse
import collections
import csv
import datetime
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FUNCS = ROOT / "ghidra" / "export" / "functions.csv"
OBJECTS = ROOT / "orig" / "ps2proto" / "pc_objects.csv"
REPORT = ROOT / "build" / "report.json"
OUT = ROOT / "docs" / "progress.md"
LIBRARY_START = 0x5B4A34  # MSVC CRT and EH funclets (docs/binary-notes.md)


def module_of(obj):
    """'nu2api.bionicleps2/nucore/nufile.o' -> 'nu2api/nucore'; 'Bionicle.ps2/x.o' -> 'Bionicle'."""
    if not obj or "|" in obj:
        return "(unplaced)"
    parts = obj.split("/")
    project = parts[0].split(".")[0]
    return "/".join([project] + parts[1:-1][:1]) if len(parts) > 2 else project


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--no-write", action="store_true")
    args = ap.parse_args()

    funcs = {}
    for row in csv.DictReader(open(FUNCS)):
        a = int(row["address"], 16)
        if a < LIBRARY_START:  # thunks too: single-jump functions such as NuLstAlloc
            funcs[a] = int(row["size"])
    placed = {}
    if OBJECTS.exists():
        for row in csv.DictReader(open(OBJECTS)):
            if row["status"] in ("named", "inside"):
                placed[int(row["pc_address"], 16)] = row["object"]

    subprocess.run([str(ROOT / "tools" / "reccmp"), "reccmp", "--target", "BIONICLE", "--silent",
                    "--json", str(REPORT)], check=True, capture_output=True)
    entries = json.load(open(REPORT))["data"]
    # Identical code that reccmp scores below 100% because it can't name an address
    # (tools/offsetmatch.py) counts as effective.
    sys.path.insert(0, str(ROOT / "tools"))
    import offsetmatch
    identical = offsetmatch.find(REPORT)
    status = {}
    for e in entries:
        a = int(e["address"], 16)
        if a not in funcs:
            continue
        if e.get("stub"):
            status[a] = "stub"
        elif e["matching"] == 1.0:
            status[a] = "exact"
        elif e.get("effective") or e["address"] in identical:
            status[a] = "effective"
        else:
            status[a] = "partial"

    done = {a for a, s in status.items() if s in ("exact", "effective")}
    total_bytes = sum(funcs.values())
    done_bytes = sum(funcs[a] for a in done)
    counts = collections.Counter(status.values())

    modules = collections.defaultdict(lambda: [0, 0, 0, 0])  # funcs, bytes, done funcs, done bytes
    for a, size in funcs.items():
        m = modules[module_of(placed.get(a))]
        m[0] += 1
        m[1] += size
        if a in done:
            m[2] += 1
            m[3] += size

    today = datetime.date.today().isoformat()
    summary = (f"{len(done)}/{len(funcs)} functions ({100 * len(done) / len(funcs):.2f}%), "
               f"{done_bytes}/{total_bytes} bytes ({100 * done_bytes / total_bytes:.2f}%)")
    print(summary)
    if args.no_write:
        return

    history = []
    if OUT.exists():
        text = OUT.read_text()
        if "## History" in text:
            history = [l for l in text.split("## History", 1)[1].splitlines() if l.startswith("| 20")]
    row = (f"| {today} | {counts['exact']} | {counts['effective']} | {counts['partial']} | "
           f"{100 * done_bytes / total_bytes:.2f}% |")
    if history and history[-1].split("|")[1].strip() == today:
        history[-1] = row
    elif not history or history[-1].split("|")[2:] != row.split("|")[2:]:
        history.append(row)

    lines = [
        "# Progress",
        "",
        "Generated by `tools/progress.py`; don't edit by hand (the history table is kept).",
        "",
        f"**Matched: {summary}** of game + engine code.",
        "",
        "| | Functions |",
        "|---|---:|",
        f"| exact (100%) | {counts['exact']} |",
        f"| effective (same code; register/ordering differences, or addresses reccmp can't name) | {counts['effective']} |",
        f"| partial (in progress) | {counts['partial']} |",
        f"| stubs | {counts['stub']} |",
        f"| total, game + engine | {len(funcs)} |",
        "",
        "Excludes the statically linked MSVC CRT and EH funclets (from `0x5b4a34`).",
        "",
        "## By module",
        "",
        "Modules come from the PS2 prototype's source tree (`docs/ps2-prototype.md`);",
        "`(unplaced)` is code not yet assigned to an original file.",
        "",
        "| Module | Functions | Matched | Bytes matched |",
        "|---|---:|---:|---:|",
    ]
    for name, (n, b, dn, db) in sorted(modules.items(), key=lambda kv: (-kv[1][2], -kv[1][0])):
        lines.append(f"| `{name}` | {n} | {dn} | {100 * db / b:.1f}% |")
    lines += ["", "## History", "", "| Date | Exact | Effective | Partial | Bytes |", "|---|---:|---:|---:|---:|"]
    lines += history
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
